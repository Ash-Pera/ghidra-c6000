"""Generate packet-shadow register tables and commits for c6000.sinc."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANG = ROOT / "data/languages"


def register_tables():
    lines = ["# Generated by tools/gen_packet_sinc.py; do not edit by hand."]
    registers = [f"A{i}" for i in range(32)] + [f"B{i}" for i in range(32)]
    for slot in (0, 1):
        field = f"c_pkt_write{slot}"
        lines += [
            f'PktReg{slot}: "none" is {field}=0 {{ export C6000_PKT_DUMMY; }}',
            f'PktShadow{slot}: "none" is {field}=0 {{ export C6000_PKT_DUMMY; }}',
        ]
        for index, name in enumerate(registers, 1):
            shadow = "C6000_PKT_" + name
            lines.append(
                f'PktReg{slot}: "{name}" is {field}={index} {{ export {name}; }}')
            lines.append(
                f'PktShadow{slot}: "{name}" is {field}={index} {{ export {shadow}; }}')
    for slot in (0, 1):
        field = f"c_pkt_write{slot}"
        for index in range(65):
            lines.append(
                f'PktSelector{slot}: "" is {field}={index} {{ export {index}:1; }}')
    for code in range(14):
        lines.append(
            f'PktPredicate: "" is c_pkt_pred={code} {{ export {code}:1; }}')
    for start in range(2):
        for end in range(2):
            for branch_end in range(2):
                timing = start | (end << 1) | (branch_end << 2)
                lines.append(
                    f'PktTiming: "" is c_pkt_start={start} & c_pkt_end={end} '
                    f'& c_pkt_branch_end={branch_end} {{ export {timing}:1; }}')
    return "\n".join(lines) + "\n"


def commit_macro():
    lines = ["# Generated by tools/gen_packet_sinc.py; do not edit by hand.",
             "macro c6000_pkt_condition(code, take) {",
             "  take = (code == 0);"]
    predicates = [
        (2, "B0", "!="), (3, "B0", "=="), (4, "B1", "!="),
        (5, "B1", "=="), (6, "B2", "!="), (7, "B2", "=="),
        (8, "A1", "!="), (9, "A1", "=="), (10, "A2", "!="),
        (11, "A2", "=="), (12, "A0", "!="), (13, "A0", "=="),
    ]
    for code, register, operator in predicates:
        lines += [
            f"  if (code != {code}) goto <pkt_condition_{code}>;",
            f"  take = ({register} {operator} 0);",
            f"  <pkt_condition_{code}>",
        ]
    lines += ["}", "", "macro c6000_pkt_commit_all() {"]
    registers = [f"A{i}" for i in range(32)] + [f"B{i}" for i in range(32)]
    for index, name in enumerate(registers):
        shadow = "C6000_PKT_" + name
        lines += [
            f"  if ((C6000_PKT_MASK & (1:8 << {index})) == 0) goto <pkt_commit_{index}>;",
            f"  {name} = {shadow};",
            f"  <pkt_commit_{index}>",
        ]
    lines += ["  C6000_PKT_MASK = 0;", "}"]
    return "\n".join(lines) + "\n"


def main():
    (LANG / "c6000_packet_registers.sinc").write_text(register_tables())
    (LANG / "c6000_packet_semantics.sinc").write_text(commit_macro())


if __name__ == "__main__":
    main()
