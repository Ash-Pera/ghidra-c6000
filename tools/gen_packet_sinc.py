"""Generate the packet-staging tables for c6000.sinc.

Each table is selected by context alone, so a staged packet's p-code has no
branches and touches only the registers the scheduler named.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANG = ROOT / "data/languages"
REGISTERS = [f"A{i}" for i in range(32)] + [f"B{i}" for i in range(32)]


def register_tables():
    lines = ["# Generated by tools/gen_packet_sinc.py; do not edit by hand."]
    for slot in (0, 1):
        write, chain, old = f"c_pkt_write{slot}", f"c_pkt_chain{slot}", f"C6000_PKT_OLD{slot}"
        lines += [f"PktIn{slot}: is {write}=0 {{ }}", f"PktOut{slot}: is {write}=0 {{ }}"]
        for index, name in enumerate(REGISTERS, 1):
            shadow = "C6000_PKT_" + name
            # A later writer of the register continues from the earlier writer's shadow.
            lines += [
                f"PktIn{slot}: is {write}={index} & {chain}=0 {{ {old} = {name}; }}",
                f"PktIn{slot}: is {write}={index} & {chain}=1 "
                f"{{ {old} = {name}; {name} = {shadow}; }}",
                f"PktOut{slot}: is {write}={index} {{ {shadow} = {name}; {name} = {old}; }}",
            ]
    for slot in (0, 1):
        commit = f"c_pkt_commit{slot}"
        lines.append(f"PktCommit{slot}: is {commit}=0 {{ }}")
        for index, name in enumerate(REGISTERS, 1):
            lines.append(f"PktCommit{slot}: is {commit}={index} {{ {name} = C6000_PKT_{name}; }}")
    return "\n".join(lines) + "\n"


def main():
    (LANG / "c6000_packet_registers.sinc").write_text(register_tables())


if __name__ == "__main__":
    main()
