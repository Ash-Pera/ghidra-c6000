#!/usr/bin/env python3
"""Generate constant SLEIGH delay-byte choices for late proven return windows.

SPRUFE8B 3.5 / 4.2.6; SLEIGH 7.11 counts bytes, not cycles/instructions.
"""
from pathlib import Path
p=Path(__file__).resolve().parents[1]/"data/languages/c6000_flow_delay.sinc"
lines=["# Generated by tools/gen_flow_delay.py. Apache-2.0.",
       "# SPRUFE8B 3.5 and 4.2.6; SLEIGH 7.11: operand is minimum byte count."]
for n in range(0,256,2):
    ordinary = f"delayslot({n});" if n else ""
    commit = [
        "if (PktSelector0 == 0) goto <pkt_branch_write1>;",
        "if (C6000_PKT_TAKE == 0) goto <pkt_branch_skip0>;",
        "C6000_PKT_MASK = C6000_PKT_MASK & ~(1:8 << (PktSelector0 - 1));",
        "<pkt_branch_skip0>",
        "<pkt_branch_write1>",
        "if (PktSelector1 == 0) goto <pkt_branch_commit>;",
        "if (C6000_PKT_TAKE == 0) goto <pkt_branch_skip1>;",
        "C6000_PKT_MASK = C6000_PKT_MASK & ~(1:8 << (PktSelector1 - 1));",
        "<pkt_branch_skip1>",
        "<pkt_branch_commit>",
        "c6000_pkt_commit_all();",
    ]
    lines.append(
        f"CFlowDelay: is c_flow_delay={n} & c_pkt_branch_end=0 "
        f"& PktSelector0 & PktSelector1 {{ {ordinary} }}")
    lines.append(
        f"CFlowDelay: is c_flow_delay={n} & c_pkt_branch_end=1 "
        f"& PktSelector0 & PktSelector1 {{ {' '.join(commit)} {ordinary} }}")
p.write_text("\n".join(lines)+"\n")
