#!/usr/bin/env python3
"""Generate constant SLEIGH delay-byte choices for late proven return windows.

SPRUFE8B 3.5 / 4.2.6; SLEIGH 7.11 counts bytes, not cycles/instructions.
"""
from pathlib import Path
p=Path(__file__).resolve().parents[1]/"data/languages/c6000_flow_delay.sinc"
lines=["# Generated by tools/gen_flow_delay.py. Apache-2.0.",
       "# SPRUFE8B 3.5 and 4.2.6; SLEIGH 7.11: operand is minimum byte count."]
for n in range(0,256,2):
    body=f"delayslot({n});" if n else ""
    lines.append(f"CFlowDelay: is c_flow_delay={n} {{ {body} }}")
p.write_text("\n".join(lines)+"\n")
